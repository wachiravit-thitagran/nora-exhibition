#!/bin/sh
# เริ่มรีเลย์คำสั่งไว้เบื้องหลัง ก่อนที่ entrypoint จะ exec nginx
#
# อิมเมจ nginx รันทุกไฟล์ใน /docker-entrypoint.d/ ตามลำดับชื่อ แล้วค่อย exec nginx
# สคริปต์นี้จึงต้อง "ไม่บล็อก" — สั่งงานเบื้องหลังแล้ว return ทันที
#
# วนรีสตาร์ตเอง เพราะไม่มีตัว supervise ในคอนเทนเนอร์
# ถ้ารีเลย์ตาย nginx (PID 1) ยังเสิร์ฟสไลด์ต่อได้ตามปกติ — สไลด์ไม่ได้พึ่งรีเลย์
# ในการเดินหน้า จอยังตรงกันเองด้วยนาฬิกาโลก แค่สั่งจากมือถือไม่ได้ชั่วคราว
set -e

: "${RELAY_PORT:=10097}"

echo "[relay] เริ่มรีเลย์คำสั่งที่พอร์ต ${RELAY_PORT}"

(
  while true; do
    PORT="$RELAY_PORT" node /app/server.mjs || true
    echo "[relay] รีเลย์หยุดทำงาน เริ่มใหม่ในอีก 2 วินาที" >&2
    sleep 2
  done
) &
